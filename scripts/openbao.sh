#!/usr/bin/env bash
# Workstation-side OpenBao tasks. Usage: scripts/openbao.sh <init|unseal|seed|k8s-auth|env>
set -euo pipefail
cd "$(dirname "$0")/.."

INV=inventory.yaml
P=.local/pki
INIT_FILE=.local/openbao-init.json
APPROLE_FILE=.local/approle.json

BAO_ADDR="https://$(yq '.nodes.openbao.ip' "$INV"):8200"
BAO_CACERT="$P/homelab-ca.crt"
export BAO_ADDR BAO_CACERT

api() { curl -s --cacert "$BAO_CACERT" "$BAO_ADDR/v1/$1"; }

wait_up() {
  until api sys/health >/dev/null; do
    echo "waiting for OpenBao at $BAO_ADDR ..."
    sleep 10
  done
}

use_root_token() {
  if [ -z "${BAO_TOKEN:-}" ]; then
    [ -f "$INIT_FILE" ] || { echo "Set BAO_TOKEN (root token from your password manager)"; exit 1; }
    BAO_TOKEN=$(jq -r .root_token "$INIT_FILE")
  fi
  export BAO_TOKEN
}

# IPs of every node with a given role, as a CIDR list: 192.168.1.41/32,192.168.1.42/32
role_cidrs() {
  yq "[.nodes[] | select(.role == \"$1\") | .ip + \"/32\"] | join(\",\")" "$INV"
}

cmd_init() {
  wait_up
  if [ "$(api sys/init | jq -r .initialized)" = "true" ]; then
    echo "OpenBao already initialised"
    return
  fi
  # One unseal key is plenty for a homelab. Use 5/3 if you want to practise Shamir.
  bao operator init -key-shares=1 -key-threshold=1 -format=json > "$INIT_FILE"
  chmod 600 "$INIT_FILE"
  cat <<EOF

  OpenBao initialised. The unseal key and root token are in $INIT_FILE.
  >>> Copy both into your password manager now. <<<
  Once the lab is up you can delete that file; scripts then ask for BAO_TOKEN instead.

EOF
}

cmd_unseal() {
  wait_up
  if [ "$(api sys/seal-status | jq -r .sealed)" = "false" ]; then
    echo "OpenBao is unsealed"
    return
  fi
  if [ -f "$INIT_FILE" ]; then
    bao operator unseal "$(jq -r '.unseal_keys_b64[0]' "$INIT_FILE")" >/dev/null
  else
    bao operator unseal   # prompts for the key
  fi
  echo "OpenBao unsealed"
}

cmd_seed() {
  use_root_token

  bao secrets list -format=json | jq -e '."kv/"' >/dev/null || bao secrets enable -path=kv kv-v2
  bao auth list -format=json | jq -e '."approle/"' >/dev/null || bao auth enable approle

  # Policies: each role reads only what it needs.
  bao policy write etcd - <<'EOF'
path "kv/data/k8s/etcd" { capabilities = ["read"] }
EOF
  bao policy write k8s_control - <<'EOF'
path "kv/data/k8s/control" { capabilities = ["read"] }
path "kv/data/k8s/join"    { capabilities = ["read"] }
EOF
  bao policy write k8s_worker - <<'EOF'
path "kv/data/k8s/join" { capabilities = ["read"] }
EOF

  # AppRoles, usable only from that role's node IPs.
  for role in etcd k8s_control k8s_worker; do
    cidrs=$(role_cidrs "$role")
    bao write "auth/approle/role/$role" \
      token_policies="$role" token_ttl=5m token_max_ttl=15m \
      secret_id_ttl=0 secret_id_num_uses=0 \
      secret_id_bound_cidrs="$cidrs" token_bound_cidrs="$cidrs" >/dev/null
  done

  # Secrets generated by scripts/pki.sh
  bao kv put kv/k8s/etcd \
    etcd_ca_crt=@"$P/etcd-ca.crt" \
    etcd_server_crt=@"$P/etcd-server.crt" \
    etcd_server_key=@"$P/etcd-server.key" >/dev/null
  bao kv put kv/k8s/control \
    k8s_ca_crt=@"$P/k8s-ca.crt" \
    k8s_ca_key=@"$P/k8s-ca.key" \
    etcd_ca_crt=@"$P/etcd-ca.crt" \
    etcd_client_crt=@"$P/etcd-apiserver-client.crt" \
    etcd_client_key=@"$P/etcd-apiserver-client.key" >/dev/null
  bao kv put kv/k8s/join \
    join_token="$(cat "$P/join-token")" \
    join_ca_hash="$(cat "$P/join-ca-hash")" >/dev/null

  # Keep the Proxmox token here too, so it can live outside your shell history.
  if [ -n "${PROXMOX_VE_API_TOKEN:-}" ]; then
    bao kv put kv/infra/proxmox api_token="$PROXMOX_VE_API_TOKEN" >/dev/null
  fi

  # A demo app secret, synced into Kubernetes by k8s/platform/demo.
  bao kv get kv/apps/demo >/dev/null 2>&1 ||
    bao kv put kv/apps/demo username=demo password="$(openssl rand -hex 12)" >/dev/null

  # AppRole credentials for OpenTofu to hand to each VM via cloud-init.
  if [ ! -f "$APPROLE_FILE" ]; then
    echo '{}' > "$APPROLE_FILE"
    for role in etcd k8s_control k8s_worker; do
      role_id=$(bao read -field=role_id "auth/approle/role/$role/role-id")
      secret_id=$(bao write -f -field=secret_id "auth/approle/role/$role/secret-id")
      jq --arg r "$role" --arg i "$role_id" --arg s "$secret_id" \
        '.[$r] = {role_id: $i, secret_id: $s}' "$APPROLE_FILE" > "$APPROLE_FILE.tmp"
      mv "$APPROLE_FILE.tmp" "$APPROLE_FILE"
    done
    chmod 600 "$APPROLE_FILE"
  fi
  echo "OpenBao seeded: kv engine, policies, AppRoles, cluster secrets"
}

# Lets the External Secrets Operator log in with its Kubernetes service account.
cmd_k8s_auth() {
  use_root_token
  cp_ip=$(yq '[.nodes[] | select(.role == "k8s_control")][0].ip' "$INV")

  bao auth list -format=json | jq -e '."kubernetes/"' >/dev/null || bao auth enable kubernetes
  # No reviewer JWT: OpenBao uses the caller's own token for the TokenReview,
  # which is why the ESO service account is bound to system:auth-delegator.
  bao write auth/kubernetes/config \
    kubernetes_host="https://$cp_ip:6443" \
    kubernetes_ca_cert=@"$P/k8s-ca.crt" >/dev/null

  bao policy write eso - <<'EOF'
path "kv/data/apps/*"     { capabilities = ["read"] }
path "kv/metadata/apps/*" { capabilities = ["read", "list"] }
EOF
  bao write auth/kubernetes/role/eso \
    bound_service_account_names=external-secrets \
    bound_service_account_namespaces=external-secrets \
    token_policies=eso token_ttl=1h >/dev/null
  echo "Kubernetes auth ready: ESO can read kv/apps/*"
}

# eval "$(scripts/openbao.sh env)"  -> use the bao CLI against the lab
cmd_env() {
  echo "export BAO_ADDR=$BAO_ADDR BAO_CACERT=$PWD/$BAO_CACERT"
}

case "${1:-}" in
  init) cmd_init ;;
  unseal) cmd_unseal ;;
  seed) cmd_seed ;;
  k8s-auth) cmd_k8s_auth ;;
  env) cmd_env ;;
  *) echo "usage: $0 <init|unseal|seed|k8s-auth|env>"; exit 1 ;;
esac
